const interfaceMessages = {
  "ru-RU": Object.fromEntries(Object.keys(germanMessages).map(key => [key, key])),
  "de-DE": germanMessages,
};
const defaultInterfaceLanguage = "de-DE";
let interfaceLanguage = defaultInterfaceLanguage;

function savedLanguage(settings) {
  return settings.language === "ru-RU" ? "ru-RU" : defaultInterfaceLanguage;
}

// Tagged templates keep user values separate from the translated sentence.
function t(message, ...values) {
  const key = typeof message === "string" ? message
    : message.reduce((text, part, i) => text + (i ? `{${i - 1}}` : "") + part, "");
  const translated = interfaceMessages[interfaceLanguage][key];
  return values.length ? translated.replace(/\{(\d+)\}/g, (_, i) => values[i]) : translated;
}

const eventCountKeys = { one: "{0} событие", few: "{0} события", other: "{0} событий" };
function eventCount(count) {
  const form = new Intl.PluralRules(interfaceLanguage).select(count);
  return t(eventCountKeys[form] || eventCountKeys.other, count);
}

// Native validation otherwise follows the browser's language. Leave each
// form's more specific validation messages in place when it supplies one.
document.addEventListener("invalid", event => {
  const field = event.target;
  if (!field.validity || field.validity.customError) return;
  field.setCustomValidity(field.validity.valueMissing ? t("Заполните это поле.") : t("Проверьте значение поля."));
  setTimeout(() => field.setCustomValidity(""), 0);
}, true);

// Bind the original HTML before the calendar renders any user content.
const interfaceBindings = [];
function bindInterfaceAttribute(element, attribute, key) {
  const update = () => element.setAttribute(attribute, t(key));
  interfaceBindings.push(update);
  update();
}

const interfaceText = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (interfaceText.nextNode()) {
  const node = interfaceText.currentNode;
  const original = node.data;
  const key = original.trim();
  if (Object.hasOwn(germanMessages, key)) {
    interfaceBindings.push(() => { node.data = original.replace(key, () => t(key)); });
  }
}
for (const attribute of ["aria-label", "title", "placeholder"]) {
  for (const element of document.querySelectorAll(`[${attribute}]`)) {
    const key = element.getAttribute(attribute);
    if (Object.hasOwn(germanMessages, key)) bindInterfaceAttribute(element, attribute, key);
  }
}

function setInterfaceLanguage(language) {
  interfaceLanguage = language;
  document.documentElement.lang = language;
  for (const update of interfaceBindings) update();
}
